// Helper to filter and search books
export function getBooks(language = 'all', category = 'all', searchQuery = '') {
  return BOOKS_CATALOG.filter((book) => {
    const matchesLang = language === 'all' || book.language === language;
    const matchesCat = category === 'all' || book.category.toLowerCase().includes(category.toLowerCase());
    const matchesSearch =
      !searchQuery ||
      book.title.toLowerCase().includes(searchQuery.toLowerCase()) ||
      book.author.toLowerCase().includes(searchQuery.toLowerCase()) ||
      book.category.toLowerCase().includes(searchQuery.toLowerCase()) ||
      book.summary.toLowerCase().includes(searchQuery.toLowerCase());

    return matchesLang && matchesCat && matchesSearch;
  });
}

export function getBookById(id) {
  return BOOKS_CATALOG.find((b) => b.id === id) || BOOKS_CATALOG[0];
}
