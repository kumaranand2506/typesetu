// Helper to filter books by language, category, or search query
export function getBooks(language = 'all', category = 'all', searchQuery = '') {
  return BOOKS_CATALOG.filter((book) => {
    if (language !== 'all' && book.language !== language) return false;
    if (category !== 'all' && book.category !== category) return false;
    if (searchQuery.trim()) {
      const q = searchQuery.toLowerCase();
      const matchTitle = book.title.toLowerCase().includes(q);
      const matchAuthor = book.author.toLowerCase().includes(q);
      const matchCategory = book.category.toLowerCase().includes(q);
      return matchTitle || matchAuthor || matchCategory;
    }
    return true;
  });
}

export function getBookById(id) {
  return BOOKS_CATALOG.find((b) => b.id === id) || BOOKS_CATALOG[0];
}
